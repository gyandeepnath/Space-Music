// Renders the station artwork (art/<id>.png, shown on lock screens and in media
// controls) and the link-preview card (og.png) from the app's own CSS.
// Run with: node tools/render-art.mjs   (needs Playwright)

import { writeFile, mkdir } from 'node:fs/promises';
import { join } from 'node:path';
import { STATIONS } from '../js/stations.js';
import { startServer, loadChromium, root } from '../test/fixtures.mjs';

const { server, origin } = await startServer();
const browser = await loadChromium().launch();
await mkdir(join(root, 'art'), { recursive: true });

const page = async (w, h, html) => {
  const p = await browser.newPage({ viewport: { width: w, height: h } });
  await p.setContent(`<!doctype html><html><head><base href="${origin}/"><link rel="stylesheet" href="css/style.css">
    <style>html,body{width:${w}px;height:${h}px;overflow:hidden;margin:0}</style></head><body>${html}</body></html>`);
  await p.evaluate(() => document.fonts.ready);
  return p;
};

for (const st of STATIONS) {
  const p = await page(
    512,
    512,
    `<div data-station="${st.id}" style="position:relative;width:512px;height:512px;display:grid;place-items:center;
      background:radial-gradient(circle at 50% 42%, color-mix(in srgb, var(--accent) 30%, transparent), transparent 62%), #04060b">
      <div class="orb" style="width:260px;height:260px;margin-top:-34px"></div>
      <div style="position:absolute;left:0;right:0;bottom:44px;text-align:center">
        <div style="font:500 22px/1 var(--mono);color:var(--accent)">${st.freq} <span style="opacity:.6">${st.unit}</span></div>
        <div style="margin-top:10px;font:700 46px/1 var(--font);letter-spacing:-0.03em;color:#fff">${st.name}</div>
      </div>
    </div>`,
  );
  await p.screenshot({ path: join(root, 'art', `${st.id}.png`) });
  await p.close();
}

const orbs = STATIONS.map(
  (st, i) => `<div data-station="${st.id}" style="display:grid;justify-items:center;gap:14px;transform:translateY(${Math.sin((i / 5) * Math.PI) * -12}px)">
    <div class="orb" style="width:${st.id === 'sun' ? 104 : 88}px;height:${st.id === 'sun' ? 104 : 88}px"></div>
    <div style="font:500 15px/1 var(--mono);color:var(--accent)">${st.freq}</div>
    <div style="font:600 17px/1 var(--font);color:#fff;opacity:.85">${st.name}</div>
  </div>`,
).join('');
const og = await page(
  1200,
  630,
  `<div data-station="iss" style="position:relative;width:1200px;height:630px;overflow:hidden;
    background:radial-gradient(ellipse 70% 60% at 80% 10%, #1c2f6b 0, transparent 70%), radial-gradient(ellipse 60% 50% at 10% 100%, #3a1a10 0, transparent 70%), #04060b">
    <div style="position:absolute;left:72px;top:70px;display:flex;align-items:center;gap:16px">
      <span class="brand-mark" style="width:40px;height:40px"></span>
      <span style="font:600 26px var(--font);color:#fff">Space Music</span>
      <span class="live-pill" style="height:28px;font-size:13px"><i></i>Live</span>
    </div>
    <h1 style="position:absolute;left:72px;top:150px;margin:0;font:700 76px/1.02 var(--font);letter-spacing:-0.04em;color:#fff;width:900px">Live radio from<br>the solar system</h1>
    <p style="position:absolute;left:72px;top:328px;margin:0;font:400 24px/1.4 var(--font);color:rgba(238,242,250,.72);width:1060px">Real-time views of space, with music composed from what you see. Tune in together.</p>
    <div style="position:absolute;left:72px;right:72px;bottom:40px;display:flex;justify-content:space-between;align-items:end">${orbs}</div>
  </div>`,
);
await og.screenshot({ path: join(root, 'og.png') });

await browser.close();
server.close();
await writeFile(join(root, 'art', 'README.md'), 'Generated by `node tools/render-art.mjs` from css/style.css. Do not edit by hand.\n');
console.log('rendered art/*.png and og.png');
